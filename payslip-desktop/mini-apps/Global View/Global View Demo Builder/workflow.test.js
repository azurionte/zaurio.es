"use strict";
const assert=require("node:assert/strict");
const C=require("./core.js");
const F=require("./workflow.js");

const workspace=C.defaultWorkspace();
assert.equal(Object.keys(workspace.countries).length,10);
assert.ok(Object.values(workspace.countries).every(p=>p.code&&p.name));
const AU=workspace.countries.AU;
assert.equal(F.templatesReady(AU),true);
assert.equal(F.patternsReady(AU),true);
const project=C.newProject(AU,"Australia 2027",2027,[]);
assert.equal(F.preparation(null,AU,C.validateProject).percent,0);
assert.equal(F.importing(null,AU).percent,0);
assert.equal(F.preparation(project,AU,C.validateProject).percent,0);
assert.equal(F.importing(project,AU).percent,0);
F.mark(project,AU,"setup",C.validateProject);
assert.equal(F.preparation(project,AU,C.validateProject).percent,20);
project.employeeIds=C.exampleEmployees(76);
assert.equal(F.preparation(project,AU,C.validateProject).percent,40);
F.mark(project,AU,"patterns",C.validateProject);
assert.equal(F.preparation(project,AU,C.validateProject).percent,60);
project.seed=87111;
const generated=C.generate(project,AU,true);
assert.ok(generated.added>100);
assert.equal(C.validateProject(project,AU).filter(f=>f.severity==="error").length,0);
assert.equal(F.preparation(project,AU,C.validateProject).percent,80);
assert.throws(()=>F.mark(project,AU,"wrong",C.validateProject));
F.mark(project,AU,"review",C.validateProject);
assert.equal(F.preparation(project,AU,C.validateProject).percent,100);
assert.equal(F.importing(project,AU).percent,0);
const jan=C.batchEvents(project,["P2001","P2010"],1,1);
assert.ok(jan.length>0);
const revs={};
jan.forEach(e=>revs[e.id]=e.revision);
project.batches.push({id:"batch-Jan",status:"downloaded",start:1,end:1,types:["P2001","P2010"],eventRevisions:revs});
assert.equal(F.importing(project,AU).percent,0,"Downloading never means imported");
project.batches[0].status="uploaded";
const progress=F.importing(project,AU);
assert.ok(progress.percent>0&&progress.percent<100);
assert.equal(progress.months[0].status,"uploaded");
const other=project.events.find(e=>e.start.slice(4,6)==="02");
assert.ok(other);
other.raw[3]=String(other.raw[3]||"").padEnd(4," ").slice(0,4);
other.revision++;
assert.equal(F.preparation(project,AU,C.validateProject).steps.review,false,"Editing an event invalidates the plan approval");
assert.ok(F.preparation(project,AU,C.validateProject).percent<100);
const newCountry=C.blankCountry("ZZ","Synthetic Country","EUR");
assert.equal(F.templatesReady(newCountry),false);
assert.equal(F.patternsReady(newCountry),false);
assert.throws(()=>F.mark(C.newProject(newCountry,"New",2027,[]),newCountry,"setup",C.validateProject));
console.log("Guided GlobalView workflow: preparation 0→100%, import milestones, revisions and custom country tests PASS.");